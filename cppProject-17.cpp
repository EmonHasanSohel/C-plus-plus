#include <iostream>
using namespace std;
int main (){
    int a=2;
    int b=++a;
    cout<<"a:"<<a<<endl;
    cout<<"b:"<<b<<endl;

    int c=2;
    int d=--c;
    cout<<"c:"<<c<<endl;
    cout<<"d:"<<d<<endl;

    int x=2;
    int y=x++;
    cout<<"x:"<<x<<endl;
    cout<<"y:"<<y<<endl;

    int m=2;
    int n=m--;
    cout<<"m:"<<m<<endl;
    cout<<"n:"<<n<<endl;



}